import type { FxFunctionDef } from "../api/types";
import { builtinFunctions } from "./index";
import { functionDocs } from "./docs";

/** Parameter names of a definition's `evaluate`, read from its source; `[x]` marks an optional one, `...x` a rest. */
export function parameterNames(def: FxFunctionDef): string[] {
  if (def.deferEvaluation && def.params) { return def.params.map(p => p.name); }
  const src = def.evaluate?.toString() ?? "";
  const m = /^(?:async\s+)?(?:function\s*[\w$]*\s*)?\(([^)]*)\)|^([\w$]+)\s*=>/.exec(src);
  const list = (m?.[1] ?? m?.[2] ?? "").split(",").map(s => s.trim()).filter(Boolean);
  return list.map(p => (p.includes("=") ? `[${p.split("=")[0]!.trim()}]` : p));
}

function signature(def: FxFunctionDef): string {
  const optional = new Set(functionDocs[def.name]?.optional);
  const params = parameterNames(def).map(p => (optional.has(p) ? `[${p}]` : p));
  return `${def.name}(${params.join(", ")})`;
}

const GROUPS: ReadonlyArray<readonly [string, (d: FxFunctionDef) => boolean]> = [
  ["Operators", d => !!d.operator],
  ["Conditional and errors", d => ["ifElse", "ifNull", "ifUndefined", "ifNullOrUndefined", "notNull", "throw", "catch"].includes(d.name)],
  ["Collections", d => ["assign", "map", "sort", "reverse", "indexOf", "findIndex", "filter", "reduce", "find", "slice", "splice", "concat",
    "min", "findMin", "max", "findMax", "avg", "length", "range", "item", "first", "last"].includes(d.name)],
  ["Strings", d => ["toString", "substr", "substring", "startsWith", "endsWith", "contains", "split", "join", "toUpperCase", "toLowerCase",
    "toTitleCase", "toSnakeCase", "toCamelCase", "trim", "trimLeft", "trimRight", "replace"].includes(d.name)],
  ["Dates and times", d => ["now", "dateTime", "toISODateTime", "toISOLocalDateTime"].includes(d.name)],
  ["Math", d => d.name.startsWith("math~")],
  ["Other", () => true]
];

const cell = (s: string) => s.replace(/\|/g, "\\|");

/** The Markdown of docs/FUNCTIONS.md, generated from the built-in definitions and `functionDocs`. */
export function functionReference(): string {
  const out: string[] = [
    "# Built-in function reference",
    "",
    "<!-- Generated by `npm run docs` from src/stdlib (definitions and docs.ts). Do not edit by hand. -->",
    "",
    "Every function can be called as `name(a, b)` or chained as `a:name(b)`, which passes `a` as the first argument.",
    "Operators are functions too: `$a + $b` is `add($a, $b)`. *Pure* functions have no side effects and depend only on their arguments;",
    "the optimizer may evaluate them at compile time. Optional parameters are in `[brackets]`.",
    ""
  ];
  const remaining = new Set(builtinFunctions);
  for (const [title, test] of GROUPS) {
    const defs = [...remaining].filter(test);
    if (!defs.length) { continue; }
    defs.forEach(d => remaining.delete(d));
    out.push(`## ${title}`, "");
    if (title === "Math") {
      const fns = defs.filter(d => !/^[A-Z0-9_]+$/.test(d.name.slice(5)));
      const consts = defs.filter(d => /^[A-Z0-9_]+$/.test(d.name.slice(5)));
      out.push("Each is the JavaScript `Math` function of the same name, called with the same arguments, e.g. `math~floor($.x / 10)`.",
        `\`math~random\` is the only impure one. Constants take no arguments: ${consts.map(d => `\`${d.name}\``).join(", ")}.`, "",
        `Functions: ${fns.map(d => `\`${d.name}\``).join(", ")}.`, "");
      continue;
    }
    const isOps = title === "Operators";
    out.push(isOps ? "| Function | Operator | Precedence | Description |" : "| Function | Pure | Description |",
      isOps ? "|---|---|---|---|" : "|---|---|---|");
    for (const def of defs) {
      const doc = functionDocs[def.name];
      const text = doc ? `${doc.summary}${doc.example ? ` Example: \`${doc.example}\`` : ""}` : "";
      const op = def.operator;
      out.push(isOps
        ? `| \`${signature(def)}\` | \`${cell(op!.symbol)}\`${op!.isUnary ? " (prefix)" : ""} | ${op!.precedence}${op!.assoc === "right" ? ", right" : ""} | ${cell(text)} |`
        : `| \`${signature(def)}\` | ${def.pure ? "yes" : "no"} | ${cell(text)} |`);
    }
    out.push("");
  }
  return out.join("\n");
}
